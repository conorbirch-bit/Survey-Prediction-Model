"""One-attempt approvals from Conor's 30 October audit.

The JSON is deployed with the app; it is never regenerated by an LLM at run time.
Fresh appointment status and history always outrank a saved approval.
"""
import json
import math
from pathlib import Path

import pandas as pd

AUDIT_FILE = Path(__file__).with_name('building_decisions.json')
WEEKDAYS = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday']


def text(value):
    return '' if value is None or (not isinstance(value, (list, dict)) and pd.isna(value)) else str(value).strip()


def load_decisions(path=None):
    data = json.loads(Path(path or AUDIT_FILE).read_text(encoding='utf-8'))
    if data.get('schema_version') != 1:
        raise ValueError('Unsupported building decision file version.')
    records = data['buildings']
    keys = [r['reference'].casefold() for r in records]
    if len(keys) != len(set(keys)):
        raise ValueError('Duplicate building references in saved audit decisions.')
    return {r['reference'].casefold(): r for r in records}


def linked_appointments(record, appointments, current_work_order=''):
    """Follow the building across replacement Work Orders as well as SAs."""
    mask = appointments['Work Order Number'].isin(record.get('work_orders', []) + [current_work_order])
    for col in ('Customer Reference Code', 'Customer Reference'):
        if col in appointments:
            mask |= appointments[col].map(text).str.casefold().eq(record['reference'].casefold())
    if 'Building_Id' in appointments:
        mask |= appointments['Building_Id'].map(text).isin(record.get('building_ids', []))
    return appointments.loc[mask].copy()


def outstanding_bookings(appointments, failed_ids=()):
    """Active bookings stay protected even outside the selected exclusion weeks."""
    dates = appointments.get('Scheduled Start', pd.Series(None, index=appointments.index, dtype=object)).map(text)
    return appointments.loc[
        ~appointments['_sa_status'].isin(['completed', 'cannot complete', 'cancelled', 'canceled'])
        & ~appointments['Service Appointment ID'].isin(failed_ids)
        & (dates.ne('') | appointments['_sa_status'].isin(['scheduled', 'dispatched', 'in progress'])
           | appointments['_actual_start_dt'].notna())
    ]


def saved_decision(base, record, appointments, all_history):
    """Return an explicit decision; never infer completion/access from audit prose."""
    linked = linked_appointments(record, appointments, base['Work Order Number'])
    completed = linked.loc[linked['_sa_status'].eq('completed')]
    if not completed.empty:
        return {'Decision': 'RESOLVED', 'Reason Category': 'COMPLETED',
                'Decision Reason': 'A linked service appointment is Completed; saved audit approval is superseded.',
                'Completed Service Appointment IDs': ', '.join(completed['Service Appointment ID'])}
    history = all_history.loc[all_history['Work Order Number'].isin(set(linked['Work Order Number']) | {base['Work Order Number']})]
    failed_ids = set(linked.loc[linked['_sa_status'].eq('cannot complete'), 'Service Appointment ID']) | set(history['Old Service Appointment ID'])
    booked = outstanding_bookings(linked, failed_ids)
    if not booked.empty:
        return {'Decision': 'IGNORE', 'Reason Category': 'ALREADY_BOOKED',
                'Booking Excluded': True, 'Decision Reason': 'An outstanding appointment already exists for this building.',
                'Outstanding Appointment IDs': ', '.join(booked['Service Appointment ID'])}

    initial = set(record['failed_appointment_ids'])
    additional = failed_ids - initial
    extra_allowed = int(record.get('additional_failures_approved', 0))
    if extra_allowed:
        # A named resolution can acknowledge a visit made since the original
        # audit without guessing its SA ID. It authorises only that many extra
        # historical failures, never an unlimited bypass of future attempts.
        cutoff = pd.Timestamp(record['resolution_approved_on']).date()
        later = linked.loc[linked['Service Appointment ID'].isin(additional), '_actual_start_dt']
        later_history = history.loc[history['Old Service Appointment ID'].isin(additional), '_event_dt']
        dates = pd.to_datetime(pd.concat([later, later_history]), errors='coerce').dropna()
        expired = (len(additional) > extra_allowed
                   or base['Customer Failure Count'] + base['Metro Failure Count'] > record['customer_failures'] + record['metro_failures'] + extra_allowed
                   or any(value.date() > cutoff for value in dates))
    else:
        expired = (bool(additional) or base['Customer Failure Count'] > record['customer_failures']
                   or base['Metro Failure Count'] > record['metro_failures'])
    if expired:
        return {'Decision': 'IGNORE', 'Reason Category': 'AUDIT_APPROVAL_EXPIRED',
                'Decision Reason': 'A further failure is recorded since the audit. The saved next-attempt decision has expired; reassess this building.'}
    if not initial.issubset(failed_ids):
        return {'Decision': 'IGNORE', 'Reason Category': 'AUDIT_HISTORY_INCOMPLETE',
                'Decision Reason': 'The upload omits failed appointments present at the audit. Refresh the appointment history before using this approval.'}

    kind = record['outcome']
    result = {'Decision Source': ('Conor resolution — ' + record['resolution_approved_on'] if extra_allowed else 'Conor audit — 30 October 2026'),
              'Audit Decision Applied': True, 'Audit Instruction': record['instruction'],
              'Decision Reason': record['instruction'], 'Preferred Weekdays': [],
              'Forbidden Weekday': '', 'Forbidden Weekday Number': None,
              'Preferred Retry Period': '', 'Required Weekdays': [],
              'Call Ahead Required': kind == 'call', 'Call Phone': record.get('phone', ''),
              'Route Address Override': record.get('route_address', ''),
              'Saturday Size Exception': bool(record.get('saturday_size_exception')),
              'Review Original Surveyor': record.get('different_surveyor_from', '')}
    if kind in ('weekday', 'saturday', 'call'):
        result.update({'Decision': 'RETRY_WITH_CONSTRAINT', 'Reason Category': 'AUDITED_RETRY',
                       'Required Weekdays': ['Saturday'] if kind == 'saturday' else WEEKDAYS.copy()})
        if kind == 'saturday' and not record.get('saturday_size_exception'):
            try:
                flats = float(base.get('Source Sovereign Flat'))
            except (TypeError, ValueError):
                flats = float('nan')
            if not math.isfinite(flats) or not 1 <= flats <= 5:
                result.update({'Decision': 'IGNORE', 'Reason Category': 'SATURDAY_SIZE_UNCONFIRMED',
                               'Decision Reason': 'Saturday retry approved only for 1–5 flats. The supplied flat count does not establish that condition.'})
    elif kind == 'client':
        result.update({'Decision': 'CLIENT_ACCESS_REQUIRED', 'Reason Category': 'AUDITED_CLIENT_ACCESS',
                       'Recommended Client Action': record['instruction']})
    else:
        result.update({'Decision': 'IGNORE', 'Reason Category': 'AUDITED_HOLD'})
    return result
